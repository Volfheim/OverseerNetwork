function overseerLang() {
    return window.OVERSEER_PREFS?.language || window.readOverseerPrefs?.().language || 'ru';
}

function t(key, params = {}) {
    const lang = overseerLang();
    const template = OVERSEER_I18N[lang]?.[key] || OVERSEER_I18N.en[key] || key;
    return Object.entries(params).reduce(
        (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
        template
    );
}

function applyOverseerLanguage() {
    const lang = overseerLang();
    document.documentElement.lang = lang;
    document.querySelectorAll('[data-i18n]').forEach(el => {
        el.textContent = t(el.dataset.i18n);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder));
    });
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        el.setAttribute('title', t(el.dataset.i18nTitle));
    });
    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
        el.setAttribute('aria-label', t(el.dataset.i18nAria));
    });
}

window.OVERSEER_I18N = OVERSEER_I18N;
window.t = t;
window.applyOverseerLanguage = applyOverseerLanguage;

document.addEventListener('DOMContentLoaded', applyOverseerLanguage, { once: true });
window.addEventListener('overseer:prefs', applyOverseerLanguage);
